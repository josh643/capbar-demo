// Builds functions/_catalog.js (server-side prices) from js/products.js. Run: node tools/build_catalog.mjs
import fs from "node:fs"; import vm from "node:vm";
const ctx = { window: {} }; vm.createContext(ctx);
vm.runInContext(fs.readFileSync("js/products.js", "utf8"), ctx);
const slug = (s) => String(s || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60);
const out = {};
for (const p of ctx.window.CAPBAR_PRODUCTS) for (const c of p.colors) {
  const id = c.id || (p.id + "--" + (slug(c.name) || "color")).slice(0, 70);
  out[id] = { productId: p.id, name: p.name + " · " + c.name, cents: Math.round(p.price * 100), soldOut: !!c.soldOut };
}
fs.writeFileSync("functions/_catalog.js", "// GENERATED by tools/build_catalog.mjs - do not edit\nexport default " + JSON.stringify(out, null, 1) + ";\n");
console.log(Object.keys(out).length, "variants");
